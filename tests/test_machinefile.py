"""Test suite for machinefile. Uses examples/ as fixtures.

Two tiers:
  - compile-time: assert playbook structure and the stamp hash-chain
    semantics (determinism, append-safe, cascade-from-edit) on rendered YAML;
  - execute: run real ansible-playbook passes over sandbox Machinefiles
    (become off, stamp dir rewritten) and assert the Docker layer-cache
    contract end to end: second pass changes nothing, appending layers
    skips the past, editing a middle layer resumes there, a failed layer
    retries while its upstream stays skipped.
"""

import os
import re
import subprocess
import yaml
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
BASIC = ROOT / "examples" / "basic" / "Machinefile"
INTERLEAVE = ROOT / "examples" / "apt-sources" / "Machinefile"
UPSTREAM = ROOT / "tests" / "fixtures" / "upstream" / "Machinefile"

HASH_RE = re.compile(r"/var/lib/machinefile/([0-9a-f]{16})\b")


def _ansible_usable() -> bool:
    # Upstream breakage probe (e.g. ansible-core vs a too-new CPython:
    # markupsafe/dataclasses faults on 3.15). Self-healing: execution
    # tests re-enable the moment the interpreter+ansible combo works.
    r = subprocess.run(["uv", "run", "ansible-playbook", "--version"],
                       capture_output=True)
    return r.returncode == 0


ansible_required = pytest.mark.skipif(
    not _ansible_usable(), reason="ansible-playbook broken on this interpreter")


def plan(machinefile: Path, *extra: str) -> str:
    out = subprocess.run(
        ["uv", "run", "machine", "plan", str(machinefile), *extra],
        capture_output=True, text=True, check=True,
    ).stdout
    assert out.startswith("# Generated by machinefile")
    return out


def play(text: str) -> dict:
    parsed = yaml.safe_load(text)
    assert isinstance(parsed, list) and len(parsed) == 1
    return parsed[0]


def markers(text: str) -> list[str]:
    """Stamp marker hashes in task order (each appears twice: creates + touch)."""
    seen: list[str] = []
    for m in HASH_RE.finditer(text):
        if not seen or seen[-1] != m.group(1):
            seen.append(m.group(1))
    return seen


def task_modules(p: dict) -> list[tuple[str, dict]]:
    return [(k, v) for t in p["tasks"] for k, v in t.items()
            if k.startswith("ansible.builtin.")]


class TestChainSemantics:
    def test_deterministic(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo one\nRUN echo two\n")
        assert markers(plan(wf)) == markers(plan(wf))

    def test_append_keeps_past_layers(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo one\nRUN echo two\n")
        first = markers(plan(wf))
        assert len(first) == 2
        wf.write_text("FROM x\nRUN echo one\nRUN echo two\nRUN echo three\n")
        second = markers(plan(wf))
        assert len(second) == 3
        assert second[:2] == first[:2], "appending must not invalidate past layers"

    def test_edit_middle_cascades_downstream(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo one\nRUN echo two\nRUN echo three\n")
        before = markers(plan(wf))
        wf.write_text("FROM x\nRUN echo one\nRUN echo TWO-edited\nRUN echo three\n")
        after = markers(plan(wf))
        assert after[0] == before[0]           # upstream layer intact
        assert after[1] != before[1]           # edited layer re-runs
        assert after[2] != before[2]           # downstream invalidated too

    def test_copy_edit_invalidates_downstream(self, tmp_path):
        ctx = tmp_path / "ctx"
        ctx.mkdir()
        (ctx / "f").write_text("v1")
        wf = ctx / "M"
        wf.write_text("FROM x\nCOPY f /dest/f\nRUN echo after\n")
        before = markers(plan(wf))
        (ctx / "f").write_text("v2")  # edit a COPY'd file's bytes
        after = markers(plan(wf))
        assert after != before, "COPY content must ride the hash chain"
        # the copy task itself carries the drift guard
        copy_task = next(t for t in play(plan(wf))["tasks"]
                         if "ansible.builtin.copy" in t)
        assert "checksum" in str(copy_task)

    def test_comment_edit_inert(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("RUN echo one\n")
        before = markers(plan(wf))
        wf.write_text("# just a note\nRUN echo one\n")
        assert markers(plan(wf)) == before, "annotations never enter hashes"

    def test_source_line_annotation_and_gaps(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text(
            "FROM x\n"                                   # 1
            "RUN apt-get update && apt-get install -y git\n"  # 2 -> work+mark
            "RUN echo next\n"                            # 3
        )
        text = plan(wf)
        lines = text.splitlines()
        ann2 = next(i for i, l in enumerate(lines)
                    if "# Machinefile:2: RUN apt-get update" in l)
        # annotation carries the full instruction line
        assert lines[ann2] == "  # Machinefile:2: RUN apt-get update && apt-get install -y git"
        # the whole group (work + marker) belongs to line 2; blank line after
        ann3 = next(i for i, l in enumerate(lines) if "# Machinefile:3:" in l)
        assert lines[ann3 - 1] == "", "blank line between line groups"
        # exactly one annotation per group: no duplicate above the marker
        assert lines.count("  # Machinefile:2: RUN apt-get update"
                           " && apt-get install -y git") == 1
        assert len(yaml.safe_load(text)) == 1  # still valid YAML


class TestInstructionMapping:
    def test_stamp_pair_shape(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo hi\n")
        tasks = play(plan(wf))["tasks"]
        assert tasks[0]["name"] == "ensure stamp dir"
        work, mark = tasks[1], tasks[2]
        assert work["args"]["creates"].startswith("/var/lib/machinefile/")
        assert mark["ansible.builtin.command"]["cmd"].startswith("touch ")
        assert mark["args"]["creates"] == work["args"]["creates"]
        assert mark["name"].startswith("mark:")

    def test_env_is_layer_scoped(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text(
            "FROM x\nENV PATH=/opt/tools/bin:$PATH\nRUN echo run\n")
        text = plan(wf)
        p = play(text)
        assert "profile.d" not in text
        run_cmds = [a["cmd"] for m, a in task_modules(p)
                    if m == "ansible.builtin.shell"]
        assert run_cmds and "export PATH=/opt/tools/bin:$PATH" in run_cmds[0]
        # literal $PATH survives for the apply-time shell
        assert "$PATH" in run_cmds[0]

    def test_user_becomes_become_user(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo rootish\nUSER deploy\nRUN echo dep\n")
        shell_tasks = [t for t in play(plan(wf))["tasks"]
                       if "ansible.builtin.shell" in t]
        assert all("become_user" not in t for t in shell_tasks[:1])
        assert all(t.get("become_user") == "deploy" for t in shell_tasks[1:])

    def test_workdir_mkdir_and_chdir(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text("FROM x\nWORKDIR /srv/app\nRUN make\n")
        p = play(plan(wf))
        mods = task_modules(p)
        assert ("ansible.builtin.file",
                {"path": "/srv/app", "state": "directory"}) in mods
        run_task = next(t for t in p["tasks"] if "ansible.builtin.shell" in t)
        assert run_task["args"]["chdir"] == "/srv/app"

    def test_heredoc_preserved_verbatim(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text('FROM x\nRUN <<EOF\necho "a \'b\' line"\necho $HOME\nEOF\n')
        cmds = [a["cmd"] for m, a in task_modules(play(plan(wf)))
                if m == "ansible.builtin.shell"]
        assert 'echo "a \'b\' line"' in cmds[0]
        assert "$HOME" in cmds[0]
        assert "base64" not in str(cmds)  # block scalars: no encoding tricks

    def test_quotes_survive_yaml_roundtrip(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text(
            "FROM x\nUSER nobody\n"
            'RUN echo "it\'s a \\"tricky\\" line"\n')
        p = play(plan(wf))
        cmds = [a["cmd"] for m, a in task_modules(p)
                if m == "ansible.builtin.shell"]
        assert 'echo "it\'s a \\"tricky\\" line"' in cmds[0]

    def test_arg_default_and_override(self, tmp_path):
        wf = tmp_path / "M"
        wf.write_text('FROM x\nARG USER="runner"\nRUN echo "user=${USER}"\n')
        assert "user=runner" in plan(wf)
        assert "user=deploy" in plan(wf, "--arg", "USER=deploy")

    def test_add_url_and_tar(self, tmp_path):
        ctx = tmp_path / "ctx"
        ctx.mkdir()
        (ctx / "a.tar.gz").write_bytes(b"placeholder")
        wf = ctx / "M"
        wf.write_text(
            "FROM x\nADD https://example.com/x.bin /opt/x.bin\n"
            "ADD a.tar.gz /opt/data\n")
        mods = task_modules(play(plan(wf)))
        assert any(m == "ansible.builtin.get_url" for m, _ in mods)
        assert any("tar -xf" in str(a) for m, a in mods
                   if m == "ansible.builtin.shell"), \
            "ADD of a tarball must extract"

    def test_no_hoisting_order_preserved(self):
        p = play(plan(INTERLEAVE))
        cmds = [str(a.get("cmd", "")) for m, a in task_modules(p)]
        idx = [next(i for i, c in enumerate(cmds) if needle in c)
               for needle in ("chrome.list", "install -y google-chrome-stable")]
        assert idx[0] < idx[1], "install must stay after its apt source"

    def test_missing_source_fails_compile(self, tmp_path):
        mf = tmp_path / "Machinefile"
        mf.write_text("COPY nope.conf /etc/nope.conf\n")
        r = subprocess.run(
            ["uv", "run", "machine", "plan", str(mf)],
            capture_output=True, text=True,
        )
        assert r.returncode != 0 and "not found in context" in r.stderr


class TestUpstreamFixture:
    """Ported from ducttape-infra/machinefile test/Machinefile (Apache-2.0).

    Same observable semantics asserted on our compiled playbook: ARG
    default expansion, USER switching, COPY-then-read ordering, shebang
    tolerance. Execution-level checks live in TestAnsibleExecution (the
    upstream file writes under /tmp and switches users, which needs root).
    """

    def p(self):
        return play(plan(UPSTREAM))

    def test_compiles_with_shebang_and_scratch(self):
        # the '#!/bin/env -vS machinefile --stdin' line is a comment;
        # FROM scratch is intent, not a task
        assert len([t for t in self.p()["tasks"]
                    if "ansible.builtin.shell" in t]) == 8  # 8 RUNs x stamps

    def test_arg_default_expanded_at_compile(self):
        # command texts only: task NAMES keep the original instruction line
        cmds = str([a for _, a in task_modules(self.p())])
        assert "Current user: runner" in cmds
        assert "${USER}" not in cmds

    def test_user_switch_wraps_later_tasks(self):
        tasks = [t for t in self.p()["tasks"] if "ansible.builtin.shell" in t]
        assert all("become_user" not in t for t in tasks[:5])
        assert all(t.get("become_user") == "runner" for t in tasks[5:])

    def test_copy_then_read_order_and_drift_checksum(self):
        tasks = self.p()["tasks"]
        copy_idx = next(i for i, t in enumerate(tasks)
                        if "ansible.builtin.copy" in t)
        cat_idx = next(i for i, t in enumerate(tasks)
                       if "cat /tmp/hello" in str(t.get("ansible.builtin.shell", "")))
        assert copy_idx < cat_idx
        assert "checksum" in str(tasks[copy_idx])


def run_playbook(text: str, tmp: Path, *extra: str) -> subprocess.CompletedProcess:
    """Rewrite a plan for the sandbox (no become, local paths) and run it."""
    text = text.replace("become: true", "become: false")
    text = text.replace("/var/lib/machinefile", str(tmp / "stamps"))
    text = text.replace("/opt/mftest", str(tmp / "opt"))
    pb = tmp / "pb.yaml"
    pb.write_text(text)
    return subprocess.run(
        ["uv", "run", "ansible-playbook", str(pb),
         "-i", "localhost,", "--connection", "local", *extra],
        capture_output=True, text=True,
    )


SANDBOX = (
    "FROM scratch\n"
    "RUN echo first > {root}/a.txt\n"
    "RUN echo second > {root}/b.txt\n"
)


@ansible_required
class TestAnsibleExecution:
    """Real ansible-playbook runs proving the layer-cache contract."""

    def sandbox(self, tmp: Path, body: str | None = None) -> Path:
        ctx = tmp / "ctx"
        ctx.mkdir(exist_ok=True)
        (ctx / "opt").mkdir(exist_ok=True)
        wf = ctx / "M"
        wf.write_text((body or SANDBOX).format(root=ctx / "opt"))
        return wf

    def changed(self, out: str) -> int:
        m = re.search(r"changed=(\d+)", out)
        assert m, f"no play recap in:\n{out}"
        return int(m.group(1))

    def test_apply_then_rerun_changes_nothing(self, tmp_path):
        wf = self.sandbox(tmp_path)
        text = plan(wf)
        r1 = run_playbook(text, tmp_path)
        assert r1.returncode == 0, r1.stdout + r1.stderr
        assert (tmp_path / "ctx" / "opt" / "a.txt").read_text().strip() == "first"
        assert self.changed(r1.stdout) >= 2
        r2 = run_playbook(text, tmp_path)
        assert r2.returncode == 0, r2.stdout + r2.stderr
        assert self.changed(r2.stdout) == 0, "second apply must be a full skip"

    def test_copy_file_layer_converges(self, tmp_path):
        # Regression: the emitted checksum must be a BARE sha1 digest;
        # anything else fails every real transfer with "Copied file does
        # not match the expected checksum" (copy verifies src with sha1).
        wf = self.sandbox(tmp_path)
        (wf.parent / "f.txt").write_text("payload\n")
        wf.write_text(f"FROM scratch\nCOPY f.txt {tmp_path}/ctx/opt/copied.txt\n")
        r1 = run_playbook(plan(wf), tmp_path)
        assert r1.returncode == 0, r1.stdout + r1.stderr
        assert (tmp_path / "ctx" / "opt" / "copied.txt").read_text() == "payload\n"
        assert self.changed(r1.stdout) == 1
        r2 = run_playbook(plan(wf), tmp_path)
        assert r2.returncode == 0, r2.stdout + r2.stderr
        assert self.changed(r2.stdout) == 0, "COPY must converge natively"

    def test_append_skips_past_layers(self, tmp_path):
        wf = self.sandbox(tmp_path)
        assert run_playbook(plan(wf), tmp_path).returncode == 0
        body = SANDBOX.format(root=tmp_path / "ctx" / "opt")
        wf.write_text(body + f"RUN echo third > {tmp_path}/ctx/opt/c.txt\n")
        r = run_playbook(plan(wf), tmp_path)
        assert r.returncode == 0, r.stdout + r.stderr
        assert self.changed(r.stdout) == 2, "only the new layer + its marker change"
        assert (tmp_path / "ctx" / "opt" / "c.txt").read_text().strip() == "third"

    def test_edit_middle_layer_resumes_there(self, tmp_path):
        wf = self.sandbox(tmp_path)
        assert run_playbook(plan(wf), tmp_path).returncode == 0
        wf.write_text(SANDBOX.format(root=tmp_path / "ctx" / "opt")
                      .replace("second", "SECOND-edited"))
        r = run_playbook(plan(wf), tmp_path)
        assert r.returncode == 0, r.stdout + r.stderr
        assert (tmp_path / "ctx" / "opt" / "b.txt").read_text().strip() == "SECOND-edited"
        assert (tmp_path / "ctx" / "opt" / "a.txt").read_text().strip() == "first"

    def test_failed_layer_retries_next_apply(self, tmp_path):
        wf = self.sandbox(tmp_path)
        body = (SANDBOX.format(root=tmp_path / "ctx" / "opt")
                + f"RUN false\nRUN echo done > {tmp_path}/ctx/opt/d.txt\n")
        wf.write_text(body)
        r = run_playbook(plan(wf), tmp_path)
        assert r.returncode != 0
        assert not (tmp_path / "ctx" / "opt" / "d.txt").exists()
        # fix the failing layer: past layers stay skipped, chain resumes
        wf.write_text(body.replace("RUN false", "RUN true"))
        r2 = run_playbook(plan(wf), tmp_path)
        assert r2.returncode == 0, r2.stdout + r2.stderr
        assert (tmp_path / "ctx" / "opt" / "d.txt").read_text().strip() == "done"


class TestCLI:
    def test_trailing_verb_rotation(self, tmp_path):
        # kernel argv order for shebang direct-exec: verb may arrive both
        # before (shebang) and after (typed) the file path
        wf = tmp_path / "M"
        wf.write_text("FROM x\nRUN echo one\n")
        # reset runs for real: sandbox its stamp dir away from /var/lib
        env = {**os.environ,
               "MACHINEFILE_STAMP_DIR": str(tmp_path / "stamps")}
        for argv, out in (([str(wf), "plan"], "hosts: all"),   # ./Mf verb
                          ([str(wf), "--help"], "Usage"),      # ./Mf --help
                          ([str(wf), "reset"], "")):
            r = subprocess.run(["uv", "run", "machine", *argv],
                               capture_output=True, text=True, check=True,
                               env=env)
            assert out in r.stdout
        # bare ./Mf -> help, exit 0
        r = subprocess.run(["uv", "run", "machine", str(wf)],
                           capture_output=True, text=True, check=True)
        assert "Usage" in r.stdout and "plan" in r.stdout

    def test_reset_removes_only_its_own_file_stamps(self, tmp_path):
        stamps = tmp_path / "stamps"
        stamps.mkdir()
        env = {**os.environ, "MACHINEFILE_STAMP_DIR": str(stamps)}
        mk = tmp_path / "A"
        mk.write_text("FROM x\nRUN echo a\nRUN echo b\n")
        other = stamps / "ffffffffffffffff"  # another Machinefile's stamp
        other.touch()
        # pretend applied: create A's current stamps
        import subprocess as sp
        plan_text = sp.run(["uv", "run", "machine", "plan", str(mk)],
                           capture_output=True, text=True, check=True,
                           env=env).stdout
        for h in re.findall(rf"{re.escape(str(stamps))}/([0-9a-f]{{16}})", plan_text):
            (stamps / h).touch()
        assert len(list(stamps.iterdir())) == 3
        sp.run(["uv", "run", "machine", "reset", str(mk)], check=True, env=env)
        assert other.exists(), "must not touch other Machinefiles' markers"
        assert list(stamps.iterdir()) == [other]

    def test_help(self):
        r = subprocess.run(
            ["uv", "run", "machine", "--help"],
            capture_output=True, text=True, check=True,
        )
        assert "plan" in r.stdout and "apply" in r.stdout

    def test_output_file_and_positional_context(self, tmp_path):
        out = tmp_path / "pb.yaml"
        ctx = tmp_path / "ctx"
        ctx.mkdir()
        (ctx / "M").write_text("FROM x\nRUN true\n")
        r = subprocess.run(
            ["uv", "run", "machine", "plan", str(ctx / "M"), str(ctx),
             "-o", str(out)],
            capture_output=True, text=True, check=True,
        )
        assert "wrote" in r.stdout and out.exists()

    def test_context_twice_rejected(self, tmp_path):
        ctx = tmp_path / "ctx"
        ctx.mkdir()
        (ctx / "M").write_text("FROM x\nRUN true\n")
        r = subprocess.run(
            ["uv", "run", "machine", "plan", str(ctx / "M"), str(ctx),
             "-c", str(ctx)],
            capture_output=True, text=True,
        )
        assert r.returncode != 0 and "twice" in r.stderr

    def test_missing_machinefile_errors(self, tmp_path):
        r = subprocess.run(
            ["uv", "run", "machine", "plan", str(tmp_path / "nope")],
            capture_output=True, text=True,
        )
        assert r.returncode != 0
